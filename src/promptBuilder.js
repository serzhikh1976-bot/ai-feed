export function buildProductPrompt(item, { brand, topLevelCategories = [], fileContext = '', productType = '', descriptionRequirements = '', extraFields = {} } = {}) {
  const brandInstruction = brand
    ? `Бренд ЖЁСТКО задан пользователем: "${brand}". Используй именно это значение, не ищи бренд в тексте.`
    : `Бренд не задан пользователем. Найди бренд в названии/описании товара или используй из додаткових даних (поле brand). Если бренд определить невозможно — используй "No Name".`;

  const categoryList = topLevelCategories.map((c) => `- ${c}`).join('\n');
  
  const categoryContext = 'Категорія товару не визначена. Орієнтуйся на назву та опис.';

  const contextInstruction = fileContext
    ? `Додатковий контекст файлу: "${fileContext}". Урахуй цей контекст при формуванні назви, опису, параметрів і виборі верхньорівневої категорії.`
    : '';

  const productTypeInstruction = productType
    ? `Тип товару (вказано користувачем): "${productType}". Використовуй це для уточнення категорії та для додавання типових характеристик, що відповідають цьому типу товару.`
    : '';

  const descReqInstruction = descriptionRequirements
    ? `Особливі вимоги до опису (вказано користувачем): "${descriptionRequirements}". Обов'язково врахуй це при формуванні опису та переліку переваг.`
    : '';

  const extraFieldsEntries = Object.entries(extraFields).filter(([_, value]) => value && String(value).trim() !== '');
  const extraFieldsBlock = extraFieldsEntries.length > 0
    ? `Додаткові дані з файлу постачальника (використовуй їх як точні значення, не вигадуй):\n${extraFieldsEntries.map(([key, value]) => `- ${key}: ${value}`).join('\n')}`
    : '';

  const system = `Ты — ИИ-ассистент интернет-магазина, который готовит карточки товаров для украинских маркетплейсов Prom.ua и Rozetka.
ОБЯЗАТЕЛЬНО отвечай ТОЛЬКО валидным JSON без markdown-разметки, без пояснений до или после JSON.
ВЕСЬ сгенерированный текст (name, description, значения параметров, seoTitle, seoDescription, searchQueries) должен быть СТРОГО на украинском языке, независимо от языка исходных данных.`;

  const user = `Дані товару від постачальника (можуть бути будь-якою мовою):
- Артикул: ${item.sku}
- Назва від постачальника: ${item.name}
- Ціна: ${item.price}
- Опис/характеристики від постачальника: ${item.description || '(не вказано)'}

${brandInstruction}
${contextInstruction}
${productTypeInstruction}
${descReqInstruction}
${categoryContext}

${extraFieldsBlock ? extraFieldsBlock + '\n' : ''}

Список верхньорівневих категорій маркетплейсу (використовуй СТРОГО одне значення з цього списку дослівно, не вигадуй нове і не змінюй формулювання):
${categoryList}

Сформуй JSON строго такої структури:
{
  "name": "SEO-назва українською за формулою: [Тип товару] + [Бренд (з додаткових даних або з UI, якщо є)] + [Модель, тільки якщо вона є в додаткових даних, НЕ артикул] + [Ключові властивості (колір, розмір, матеріал тощо) з додаткових даних]. Максимум 110 символів. НІКОЛИ не використовуй артикул (sku) у назві. Якщо бренд не задано і не вдалося визначити — не додавай нічого замість нього. НЕ використовуй 'No Name' у назві. Приклад: 'Смартфон TechPhon X12 чорний 128GB'.",
  "vendor": "Бренд/виробник окремим полем. Візьми його з додаткових даних (brand) або з UI, якщо там є. Якщо бренд не визначено — постав 'No Name'. Це поле може містити 'No Name', але назва (name) — НІ.",
  "description": "Професійний структурований опис українською мовою з HTML-тегами <p>, <ul>, <li>. Описуй переваги та використання товару. НЕ пиши характеристики (розмір, колір тощо) в описі — вони мають бути ТІЛЬКИ в блоці params.",
  "params": [
    { "name": "назва характеристики українською", "value": "значення" }
  ],
  "categoryTopLevel": "одне значення дослівно зі списку категорій вище",
  "seoTitle": "SEO-заголовок до 70 символів, ключові слова + бренд + характеристика. Українською.",
  "seoDescription": "Мета-опис до 250 символів, короткий продаючий текст. Українською.",
  "searchQueries": "Пошукові фрази через кому, до 1024 символів. Тільки цільові запити. Українською."
}

Правила:
- name — максимум 110 символів, без артикулу, без емодзі, без КАПСУ, без 'No Name'. Використовуй brand, color, size, material з додаткових даних, якщо вони є.
- description — максимум 2000 символів з HTML. Заборонено: номери телефонів, посилання на сайти, заклики купити через телефон/месенджер. Не дублюй характеристики текстом, якщо вони є в params.
- searchQueries — СТРОГО заборонено слова 'купити', 'замовити', 'регіон' та назви міст/областей. Тільки цільові запити.
- vendor — використовуй бренд з додаткових даних (brand) або з UI. Якщо немає — 'No Name'. Не дублюй його в name (name має бути без 'No Name').
- params — витягни реальні характеристики (матеріал, колір, розмір, країна виробника тощо) з додаткових даних і з опису. Назви параметрів — українською.
- Якщо параметр неможливо визначити з вхідних даних — не включай його до масиву.
- categoryTopLevel — ТОЧНО збігається з одним зі значень списку вище.
- seoTitle, seoDescription, searchQueries — не дублюй їх у params.
- Поверни ТІЛЬКИ JSON, нічого більше.`;

  return { system, user };
}

export function buildCategorySelectionPrompt(generatedName, generatedDescription, candidates, fileContext = '', extraFields = {}) {
  const list = candidates.map((c) => `- id="${c.id}": ${c.path.join(' > ')}`).join('\n');

  const contextPart = fileContext 
    ? `Загальний контекст файлу: "${fileContext}". Враховуй це при виборі категорії — віддавай перевагу категоріям, що відповідають цьому контексту.` 
    : '';

  const extraFieldsEntries = Object.entries(extraFields).filter(([_, value]) => value && String(value).trim() !== '');
  const extraFieldsPart = extraFieldsEntries.length > 0
    ? `Додаткові дані про товар (використовуй їх для точнішого вибору категорії):\n${extraFieldsEntries.map(([key, value]) => `- ${key}: ${value}`).join('\n')}`
    : '';

  const system = `Ти обираєш найбільш підходящу категорію маркетплейсу для товару.
ОБОВ'ЯЗКОВО відповідай ТІЛЬКИ валідним JSON без markdown-розмітки і пояснень.
${contextPart}`;

  const user = `Товар: "${generatedName}"
Опис: ${stripHtml(generatedDescription)}

${extraFieldsPart ? extraFieldsPart + '\n' : ''}

Список кандидатів категорій (обери ОДИН, найбільш точний за змістом):
${list}

Поверни JSON строго такого вигляду:
{ "categoryId": "id одного варіанту зі списку вище, ДОСЛІВНО" }

Правила:
- categoryId ОБОВ'ЯЗКОВО має бути одним із id зі списку вище — ніколи не вигадуй новий id.
- Якщо жоден варіант не підходить ідеально — обери найближчий за змістом із запропонованих.
- Використовуй бренд, модель, колір, розмір, матеріал з додаткових даних для точнішого вибору.
- Поверни ТІЛЬКИ JSON, нічого більше.`;

  return { system, user };
}

function stripHtml(html) {
  return String(html).replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
}