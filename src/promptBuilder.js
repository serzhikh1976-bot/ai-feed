// Промпт строится строго по ТЗ (раздел 3.2–3.4):
// - обязательная локализация на украинский, независимо от языка исходника;
// - формула SEO-названия: [Тип товара] + [Бренд] + [Модель/Артикул] + [Ключевые свойства];
// - бренд: если передан пользователем — использовать жёстко, иначе искать в тексте, иначе "No Name";
// - описание — лаконичное продающее, с HTML-тегами <p>/<ul>/<li>;
// - параметры — массив пар { name, value } (материал, цвет, размер, страна и т.п.).

export function buildProductPrompt(item, { brand, topLevelCategories = [] } = {}) {
  const brandInstruction = brand
    ? `Бренд ЖЁСТКО задан пользователем: "${brand}". Используй именно это значение, не ищи бренд в тексте.`
    : `Бренд не задан пользователем. Найди бренд в названии/описании товара. Если бренд определить невозможно — используй "No Name".`;

  const categoryList = topLevelCategories.map((c) => `- ${c}`).join('\n');

  const system = `Ты — ИИ-ассистент интернет-магазина, который готовит карточки товаров для украинских маркетплейсов Prom.ua и Rozetka.
ОБЯЗАТЕЛЬНО отвечай ТОЛЬКО валидным JSON без markdown-разметки, без пояснений до или после JSON.
ВЕСЬ сгенерированный текст (name, description, значения параметров) должен быть СТРОГО на украинском языке, независимо от языка исходных данных.`;

  const user = `Данные товара от поставщика (могут быть на любом языке):
- Артикул: ${item.sku}
- Название от поставщика: ${item.name}
- Цена: ${item.price}
- Описание/характеристики от поставщика: ${item.description || '(не указано)'}

${brandInstruction}

Список верхнеуровневых категорий маркетплейса (используй СТРОГО одно значение из этого списка дословно, не изобретай новое и не изменяй формулировку):
${categoryList}

Сформируй JSON строго со следующей структурой:
{
  "name": "SEO-название на украинском по формуле: [Тип товара] + [Бренд] + [Модель/Артикул] + [Ключевые свойства (цвет/размер и т.п.)]",
  "vendor": "Бренд/производитель отдельным полем (то же значение, что и в name) — например 'Nike' или 'No Name'",
  "description": "Продающее описание на украинском, лаконичное (обычно 300-800 символов достаточно), оформленное HTML-тегами <p>, <ul>, <li> для абзацев и списков",
  "params": [
    { "name": "Колір", "value": "..." }
  ],
  "categoryTopLevel": "одно значение дословно из списка категорий выше — та ветка, к которой относится этот товар"
}

Правила:
- vendor — не дублируй как отдельный параметр в params, для бренда есть отдельное поле.
- params — извлеки из описания реальные характеристики (материал, цвет, размер, страна-производитель и т.д.), названия параметров тоже на украинском.
- Если конкретный параметр не удаётся определить из исходных данных — не включай его в массив (не выдумывай значения).
- description не должен превышать 2000 символов включая HTML-теги (пиши по существу, не растягивай искусственно).
- categoryTopLevel должен ТОЧНО совпадать по написанию с одним из значений списка выше.
- Внимание про бренд: указанный вами производитель импортируется на маркетплейс, только если он уже есть в базе производителей Prom.ua — раз мы не можем проверить это заранее, указывай бренд как есть (или "No Name"), а не выдумывай.
- Верни ТОЛЬКО JSON, ничего больше.`;

  return { system, user };
}

/**
 * Второй, узкий промпт — только выбор categoryId из короткого списка кандидатов
 * (уже отфильтрованных по top-level ветке, см. categoryDirectory.getBranchCandidates).
 * Отдельный от основного промпта вызов — дороже на одно обращение к API, но сам список
 * короткий (10-15 категорий), так что расход токенов на этот шаг небольшой.
 */
export function buildCategorySelectionPrompt(generatedName, generatedDescription, candidates) {
  const list = candidates.map((c) => `- id="${c.id}": ${c.path.join(' > ')}`).join('\n');

  const system = `Ти обираєш найбільш підходящу категорію маркетплейсу для товару.
ОБОВ'ЯЗКОВО відповідай ТІЛЬКИ валідним JSON без markdown-розмітки і пояснень.`;

  const user = `Товар: "${generatedName}"
Опис: ${stripHtml(generatedDescription)}

Список кандидатів категорій (обери ОДИН, найбільш точний за змістом):
${list}

Поверни JSON строго такого вигляду:
{ "categoryId": "id одного варіанту зі списку вище, ДОСЛІВНО" }

Правила:
- categoryId ОБОВ'ЯЗКОВО має бути одним із id зі списку вище — ніколи не вигадуй новий id.
- Якщо жоден варіант не підходить ідеально — обери найближчий за змістом із запропонованих.
- Поверни ТІЛЬКИ JSON, нічого більше.`;

  return { system, user };
}

function stripHtml(html) {
  return String(html).replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
}
