export function buildProductPrompt(item, { brand, topLevelCategories = [], fileContext = '', productType = '', descriptionRequirements = '' } = {}) {
  const brandInstruction = brand
    ? `Бренд ЖЁСТКО задан пользователем: "${brand}". Используй именно это значение, не ищи бренд в тексте.`
    : `Бренд не задан пользователем. Найди бренд в названии/описании товара. Если бренд определить невозможно — используй "No Name".`;

  const categoryList = topLevelCategories.map((c) => `- ${c}`).join('\n');
  
  const categoryContext = 'Категорія товару не визначена. Орієнтуйся на назву та опис.';

  const contextInstruction = fileContext
    ? `Додатковий контекст файлу: "${fileContext}". Урахуй цей контекст при формуванні назви, опису, параметрів і виборі верхньорівневої категорії.`
    : '';

  const productTypeInstruction = productType
    ? `Тип товару (вказано користувачем): "${productType}". Використовуй це для уточнення категорії та для додавання типових характеристик, що відповідають цьому типу товару (наприклад, для софітів — вентиляція, перфорація, стійкість до УФ).`
    : '';

  const descReqInstruction = descriptionRequirements
    ? `Особливі вимоги до опису (вказано користувачем): "${descriptionRequirements}". Обов'язково врахуй це при формуванні опису та переліку переваг.`
    : '';

  const system = `Ты — ИИ-ассистент интернет-магазина, который готовит карточки товаров для украинских маркетплейсов Prom.ua и Rozetka.
ОБЯЗАТЕЛЬНО отвечай ТОЛЬКО валидным JSON без markdown-разметки, без пояснений до или после JSON.
ВЕСЬ сгенерированный текст (name, description, значения параметров, seoTitle, seoDescription, searchQueries) должен быть СТРОГО на украинском языке, независимо от языка исходных данных.`;

  const user = `Данные товара от поставщика (могут быть на любом языке):
- Артикул: ${item.sku}
- Название от поставщика: ${item.name}
- Цена: ${item.price}
- Описание/характеристики от поставщика: ${item.description || '(не указано)'}

${brandInstruction}
${contextInstruction}
${productTypeInstruction}
${descReqInstruction}
${categoryContext}

Список верхнеуровневых категорий маркетплейса (используй СТРОГО одно значение из этого списка дословно, не изобретай новое и не изменяй формулировку):
${categoryList}

Сформируй JSON строго со следующей структурой:
{
  "name": "SEO-название на украинском по формуле: [Тип товара] + [Бренд] + [Модель/Артикул] + [Ключевые свойства (цвет/размер и т.п.)]",
  "vendor": "Бренд/производитель отдельным полем (то же значение, что и в name) — например 'Nike' или 'No Name'",
  "description": "Профессиональное, техническое описание на украинском. Додай типові для даної категорії характеристики (матеріали, розміри, технічні параметри, умови експлуатації тощо). Якщо конкретні дані відсутні — використовуй типові значення, але познач їх як «типові». Опис має бути структурованим, з HTML-тегами <p>, <ul>, <li>.",
  "params": [
    { "name": "Колір", "value": "..." }
  ],
  "categoryTopLevel": "одно значение дословно из списка категорий выше — та ветка, к которой относится этот товар",
  "seoTitle": "SEO-заголовок (HTML title) до 70 символов, включающий ключевые слова, бренд и основную характеристику. На украинском.",
  "seoDescription": "Мета-опис (HTML description) до 250 символов, короткий продающий текст с ключевыми фразами. На украинском.",
  "searchQueries": "Пошукові запити для Prom.ua — фрази через кому, до 1024 символов. Включай синонимы и популярные запросы. На украинском."
}

Правила:
- vendor — не дублируй как отдельный параметр в params.
- params — извлеки из описания реальные характеристики (материал, цвет, размер, страна-производитель и т.д.). Названия параметров тоже на украинском.
- Если конкретный параметр не удаётся определить из исходных данных — не включай его в массив, а використовуй типове значення для категорії.
- description не должен превышать 2000 символов включая HTML-теги.
- categoryTopLevel должен ТОЧНО совпадать по написанию с одним из значений списка выше.
- Внимание про бренд: указанный вами производитель импортируется на маркетплейс, только если он уже есть в базе производителей Prom.ua — раз мы не можем проверить это заранее, указывай бренд как есть (или "No Name"), а не выдумывай.
- seoTitle, seoDescription, searchQueries — не дублируй их в params.
- Верни ТОЛЬКО JSON, ничего больше.`;

  return { system, user };
}

export function buildCategorySelectionPrompt(generatedName, generatedDescription, candidates, fileContext = '') {
  const list = candidates.map((c) => `- id="${c.id}": ${c.path.join(' > ')}`).join('\n');
  const contextPart = fileContext 
    ? `Загальний контекст файлу: "${fileContext}". Враховуй це при виборі категорії — віддавай перевагу категоріям, що відповідають цьому контексту.` 
    : '';

  const system = `Ти обираєш найбільш підходящу категорію маркетплейсу для товару.
ОБОВ'ЯЗКОВО відповідай ТІЛЬКИ валідним JSON без markdown-розмітки і пояснень.
${contextPart}`;

  const user = `Товар: "${generatedName}"
Опис: ${stripHtml(generatedDescription)}

Список кандидатів категорій (обери ОДИН, найбільш точний за змістом):
${list}

Поверни JSON строго такого вигляду:
{ "categoryId": "id одного варіанту зі списку вище, ДОСЛІВНО" }

Правила:
- categoryId ОБОВ'ЯЗКОВО має бути одним із id зі списку вище — ніколи не вигадуй новий id.
- Якщо жоден варіант не підходить ідеально — обери найближчий за змістом із запропонованих.
- Поверни ТІЛЬКИ JSON, нічого більше.`;

  return { system, user };
}

function stripHtml(html) {
  return String(html).replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
}